export const L2_KNOWLEDGE =
  "三个角各自带着一种颜色。中间那些点自己不带色。某一点的颜色，是用第 1 关那三个数，把三个角色兑出来的。靠近哪个角，就更像哪个角的色。正中是三种各兑三分之一。哪个角那份是 1，这一点就是那个角的纯色。你只改三个角，整面一起变。三个角对了，整面就对了。";

